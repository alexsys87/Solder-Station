def encode(rows):
    rows = rows + [_] * (8 - len(rows))
    assert len(rows) == 8 and all(len(r) == 5 for r in rows), rows
    cols = []
    for x in range(5):
        b = 0
        for y in range(8):
            if rows[y][x] == "#":
                b |= 1 << y
        cols.append(b)
    return cols


def main():
    glyphs = UPPER + LOWER
    assert len(glyphs) == 64
    out = ["/**",
           " * @file    fonts_cyr.c",
           " * @brief   Cyrillic glyphs (Windows-1251 codes 0xC0..0xFF) for the 5x7 font,",
           " *          generated by tools/gen_font_cyr.py - do not edit.",
           " */",
           '#include "fonts.h"',
           "",
           "static const uint8_t font_cyr_data[] = {"]
    for i, (name, rows) in enumerate(glyphs):
        cols = encode(rows)
        case = "capital" if i < 32 else "small"
        out.append("    " + ", ".join(f"0x{c:02X}" for c in cols) +
                   f",   /* 0x{0xC0 + i:02X} {case} {name.upper()} */")
        if "--preview" in sys.argv:
            print(f"0x{0xC0 + i:02X} {name}")
            print("\n".join(r for r in rows))
    out += ["};",
            "",
            "const font_t font_cyr = {",
            "    8U, 1U, 0xC0U, (uint8_t)(sizeof(font_cyr_data) / 5U), 0, 5U,",
            "    0, 0, font_cyr_data, 0",
            "};",
            ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("written", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
